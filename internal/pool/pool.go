// Package pool предоставляет типобезопасный пул переиспользуемых объектов
// поверх sync.Pool. Перед возвратом объекта в пул его состояние сбрасывается
// методом Reset(), что позволяет безопасно переиспользовать «тяжёлые» объекты.
package pool

import "sync"

// Resetter ограничивает параметр пула типами, умеющими сбрасывать своё
// состояние методом Reset(). Как правило, это указатель на структуру
// (например, *Metrics), для которого сгенерирован метод Reset().
type Resetter interface {
	Reset()
}

// Pool — типобезопасная обёртка над sync.Pool для объектов типа T,
// обладающих методом Reset().
type Pool[T Resetter] struct {
	pool sync.Pool
}

// New создаёт пул объектов типа T. Функция newFn вызывается для создания
// нового объекта, когда в пуле нет свободных, и возвращает указатель на пул.
func New[T Resetter](newFn func() T) *Pool[T] {
	return &Pool[T]{
		pool: sync.Pool{
			New: func() any { return newFn() },
		},
	}
}

// Get возвращает объект из пула. Если пул пуст, объект создаётся функцией,
// переданной в New.
func (p *Pool[T]) Get() T {
	return p.pool.Get().(T)
}

// Put сбрасывает состояние объекта методом Reset() и возвращает его в пул
// для повторного использования.
func (p *Pool[T]) Put(obj T) {
	obj.Reset()
	p.pool.Put(obj)
}
